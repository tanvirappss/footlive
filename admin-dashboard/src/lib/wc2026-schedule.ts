// Map standard stadium names based on city or host
export function getStadiumForTeam(tournamentGroup: string): string {
  const group = tournamentGroup.split('-').pop()?.toUpperCase() || 'A';
  
  // Distribute stadiums based on groups to make it realistic
  switch (group) {
    case 'A':
      return 'Estadio Azteca (Mexico City)';
    case 'B':
      return 'BC Place (Vancouver)';
    case 'C':
      return 'Hard Rock Stadium (Miami)';
    case 'D':
      return 'SoFi Stadium (Los Angeles)';
    case 'E':
      return 'Mercedes-Benz Stadium (Atlanta)';
    case 'F':
      return 'NRG Stadium (Houston)';
    case 'G':
      return 'Lumen Field (Seattle)';
    case 'H':
      return 'Estadio Akron (Guadalajara)';
    case 'I':
      return 'MetLife Stadium (New York/New Jersey)';
    case 'J':
      return 'AT&T Stadium (Dallas)';
    case 'K':
      return 'Estadio BBVA (Monterrey)';
    case 'L':
      return 'Lincoln Financial Field (Philadelphia)';
    default:
      return 'MetLife Stadium (New York/New Jersey)';
  }
}
